// Package studio owns the Studio mode contracts and bounded result collector
// for NextSQL Admin (Phase 29). The HTTP/session adapter lives in the sibling
// ops package for now because the first Studio increment deliberately reuses
// the operator's already-authenticated NSQL connection. Studio still reaches
// nextsqld only through the official Go driver; it never reads storage, WAL,
// catalog, or key files directly.
