// AnalyzeRequest is the editor's pre-execution safety-check request. It
// never executes the statement or opens a driver connection.
type AnalyzeRequest struct {
	SQL string `json:"sql"`
}

// Analysis is the SQL editor's pre-execution safety classification for one
// statement, computed by parsing it with the same grammar nextsqld's own
// executor uses. It is advisory only: the server remains the sole authority
// over whether the statement is valid, authorized, or has any actual effect.
type Analysis struct {
	Kind        string   `json:"kind"`
	Destructive bool     `json:"destructive"`
	Reasons     []string `json:"reasons,omitempty"`
	// Write is true when this statement mutates data, schema, catalog,
	// server config, or transaction state — the same DML/DDL/transaction
	// classification nextsqld's own executor.isMutating uses, plus the
	// operational writes (SET CONFIG, BACKUP, cluster ops). The editor's
	// read-only production safety mode blocks a Write statement unless the
	// user explicitly overrides it; it is advisory, never a substitute for
	// server-side RBAC.
	Write bool `json:"write"`
	// RealmScoped is true for a statement that changes the realm-wide
	// principal namespace — CREATE/DROP USER, CREATE/DROP ROLE. NextSQL
	// identities are defined once per realm ("realm identities and roles
	// with database-scoped grants", docs/design-multidatabase-dbaas.md §19),
	// so the effect reaches every database in the connected realm, not just
	// the one the Studio session is pointed at. The confirm-before-run
	// dialog names the realm so a cross-database change is never silent.
	// Advisory only, exactly like Destructive/Write.
	RealmScoped bool `json:"realm_scoped,omitempty"`
}

// Analyze classifies one editor statement for a confirm-before-run warning.
// It parses sql with internal/sql/parser — the same package the executor
// binds and runs — and never opens a database connection. A parse failure is
// reported so the caller can choose to skip the warning rather than block a
// query the real executor would still accept or reject on its own terms.
func Analyze(sql string) (Analysis, error) {
	if err := ValidateSQL(sql); err != nil {
		return Analysis{}, err
	}
	stmt, err := parser.Parse(sql)
	if err != nil {
		return Analysis{}, nerr.Wrap(nerr.Syntax, "studio.Analyze", "SQL could not be parsed", err)
	}
	a := classify(stmt)
	a.Write = isWriteStmt(stmt)
	a.RealmScoped = isRealmScopedStmt(stmt)
	return a, nil
}

// isRealmScopedStmt reports whether the statement mutates the realm-wide
// principal namespace that every database in the realm shares. GRANT/REVOKE
// are deliberately excluded: a NextSQL grant carries a DatabaseID and can be
// database-scoped, and the GRANT/REVOKE builder already shows the operator
// the exact object and scope. CREATE/DROP USER and CREATE/DROP ROLE have no
// such scoping — the identity exists once for the whole realm, so running one
// against the wrong Studio connection changes access for databases the
// operator never opened.
func isRealmScopedStmt(stmt ast.Stmt) bool {
	switch stmt.(type) {
	case ast.CreateUser, ast.DropUser, ast.CreateRole, ast.DropRole:
		return true
	default:
		return false
	}
}

// isWriteStmt mirrors nextsqld's executor.isMutating (DML / DDL / workflow /
// trigger / schedule / resource-group / index DDL / transaction control) at
// the AST level — Studio has no bound plan to inspect — and additionally
// counts the operational writes the executor gates elsewhere (SET CONFIG,
// BACKUP DATABASE, MAINTAIN, and the cluster control statements). Anything
// not listed here (SELECT, SHOW, SUBSCRIBE, ANALYZE, EXPLAIN, VERIFY BACKUP,
// RESET/SET RESOURCE GROUP) is treated as a read for the read-only safety
// mode. EXPLAIN is deliberately a read even though EXPLAIN ANALYZE of a
// write does execute it — the safety mode is advisory and the confirm
// dialog still covers a destructive inner statement.
func isWriteStmt(stmt ast.Stmt) bool {
	switch stmt.(type) {
	case ast.Insert, ast.Upsert, ast.Update, ast.Delete,
		ast.CreateTable, ast.CreateDatabase, ast.DropTable, ast.AlterTable,
		ast.CreateIndex, ast.DropIndex, ast.RebuildIndex,
		ast.CreateWorkflow, ast.AlterWorkflow, ast.DropWorkflow, ast.RunWorkflow,
		ast.CreateTrigger, ast.AlterTrigger, ast.DropTrigger,
		ast.CreateSchedule, ast.AlterSchedule, ast.DropSchedule,
		ast.CreateResourceGroup, ast.AlterResourceGroup, ast.DropResourceGroup,
		ast.CancelTask,
		ast.CreateUser, ast.DropUser, ast.CreateRole, ast.DropRole, ast.Grant, ast.Revoke,
		ast.Begin, ast.Commit, ast.Rollback,
		ast.SetConfig, ast.BackupDatabase, ast.Maintain,
		ast.TransferLeader, ast.ClusterDrain, ast.ClusterMaintenance, ast.ClusterReconcileConfirm:
		return true
	default:
		return false
	}
}

func classify(stmt ast.Stmt) Analysis {
	switch s := stmt.(type) {
	case ast.Update:
		a := Analysis{Kind: "UPDATE"}
		if s.Where == nil {
			a.Destructive = true
			a.Reasons = append(a.Reasons, fmt.Sprintf(
				"No WHERE clause: this UPDATE modifies every row in %s.", s.Table))
		}
		return a
	case ast.Delete:
		a := Analysis{Kind: "DELETE"}
		if s.Where == nil {
			a.Destructive = true
			a.Reasons = append(a.Reasons, fmt.Sprintf(
				"No WHERE clause: this DELETE removes every row from %s.", s.Table))
		}
		return a
	case ast.DropTable:
		return destructive("DROP TABLE", fmt.Sprintf("Permanently drops table %s and all of its data.", s.Name))
	case ast.DropIndex:
		return destructive("DROP INDEX", fmt.Sprintf("Permanently drops index %s.", s.Name))
	case ast.DropUser:
		return destructive("DROP USER", fmt.Sprintf("Permanently removes login %s.", s.Name))
	case ast.DropRole:
		return destructive("DROP ROLE", fmt.Sprintf("Permanently removes role %s.", s.Name))
	case ast.DropWorkflow:
		return destructive("DROP WORKFLOW", fmt.Sprintf("Permanently removes workflow %s.", s.Name))
	case ast.DropTrigger:
		return destructive("DROP TRIGGER", fmt.Sprintf("Permanently removes trigger %s.", s.Name))
	case ast.DropSchedule:
		return destructive("DROP SCHEDULE", fmt.Sprintf("Permanently removes schedule %s.", s.Name))
	case ast.DropResourceGroup:
		return destructive("DROP RESOURCE GROUP", fmt.Sprintf("Permanently removes resource group %s.", s.Name))
	case ast.AlterTable:
		return classifyAlterTable(s)
	default:
		return Analysis{Kind: statementKind(stmt)}
	}
}

func classifyAlterTable(s ast.AlterTable) Analysis {
	a := Analysis{Kind: "ALTER TABLE"}
	switch cmd := s.Cmd.(type) {
	case ast.AlterDropColumn:
		a.Destructive = true
		a.Reasons = append(a.Reasons, fmt.Sprintf(
			"Permanently drops column %s and its stored data from %s.", cmd.Name, s.Table))
	case ast.AlterDropPartition:
		a.Destructive = true
		a.Reasons = append(a.Reasons, fmt.Sprintf(
			"Permanently drops partition %s and its rows from %s.", cmd.Name, s.Table))
	}
	return a
}

func destructive(kind, reason string) Analysis {
	return Analysis{Kind: kind, Destructive: true, Reasons: []string{reason}}
}

// statementKind names a non-destructive statement for display; it is never
// consulted for the destructive/reasons decision above.
func statementKind(stmt ast.Stmt) string {
	name := fmt.Sprintf("%T", stmt)
	if i := strings.LastIndex(name, "."); i >= 0 {
		name = name[i+1:]
	}
	return name
}

// Script is the ordered list of statements a script buffer splits into.
type Script struct {
	Statements []string `json:"statements"`
}

// SplitScript cuts one editor buffer into individually-runnable statements
// for Execute Script. It uses a real lexer pass — the same tokenizer the
// parser itself runs on — so a ';' inside a string, quoted identifier, or
// comment never cuts a statement early; comment-only and empty fragments are
// dropped. This deliberately re-implements internal/migrate.Split's
// three-line splitting loop rather than importing that package: migrate
// transitively pulls in internal/catalog, internal/security, and
// internal/cli, none of which belong in Studio's official-interfaces-only
// dependency footprint (see imports_test.go).
func SplitScript(sql string) ([]string, error) {
	if err := ValidateSQL(sql); err != nil {
		return nil, err
	}
	stmts, err := splitStatements(sql)
	if err != nil {
		return nil, nerr.Wrap(nerr.Syntax, "studio.SplitScript", "script could not be tokenized", err)
	}
	if len(stmts) == 0 {
		return nil, nerr.New(nerr.InvalidArgument, "studio.SplitScript", "script contains no statements")
	}
	if len(stmts) > MaxScriptStatements {
		return nil, nerr.New(nerr.Exhausted, "studio.SplitScript",
			fmt.Sprintf("script exceeds the %d-statement Studio limit", MaxScriptStatements))
	}
	return stmts, nil
}

func splitStatements(src string) ([]string, error) {
	lx := lexer.New(src)
	var stmts []string
	start := 0
	for {
		tok := lx.Next()
		if err := lx.Err(); err != nil {
			return nil, err
		}
		if tok.Kind != lexer.Semi && tok.Kind != lexer.EOF {
			continue
		}
		frag := strings.TrimSpace(src[start:tok.Pos])
		if frag != "" && !isBlankFragment(frag) {
			stmts = append(stmts, frag)
		}
		if tok.Kind == lexer.EOF {
			return stmts, nil
		}
		start = tok.Pos + len(tok.Lit)
	}
}

// isBlankFragment reports whether frag lexes to nothing but a comment (the
// lexer discards comments entirely, so such a fragment tokenizes straight to
// EOF).
func isBlankFragment(frag string) bool {
	lx := lexer.New(frag)
	tok := lx.Next()
	return tok.Kind == lexer.EOF && lx.Err() == nil
}

// stmtSpan is the byte range of one non-blank statement fragment within an
// editor buffer, whitespace already trimmed on both sides — start/end index
// the same string splitStatementSpans was given.
type stmtSpan struct{ start, end int }

// splitStatementSpans is splitStatements with the buffer offsets kept, so a
// per-statement parse diagnostic can be mapped back to the whole buffer. It
// applies the identical ';'-in-string/comment-safe lexer pass and the same
// blank/comment-only fragment filter.
func splitStatementSpans(src string) ([]stmtSpan, error) {
	lx := lexer.New(src)
	var spans []stmtSpan
	start := 0
	for {
		tok := lx.Next()
		if err := lx.Err(); err != nil {
			return nil, err
		}
		if tok.Kind != lexer.Semi && tok.Kind != lexer.EOF {
			continue
		}
		raw := src[start:tok.Pos]
		frag := strings.TrimSpace(raw)
		if frag != "" && !isBlankFragment(frag) {
			lead := start + (len(raw) - len(strings.TrimLeftFunc(raw, unicode.IsSpace)))
			spans = append(spans, stmtSpan{start: lead, end: lead + len(frag)})
		}
		if tok.Kind == lexer.EOF {
			return spans, nil
		}
		start = tok.Pos + len(tok.Lit)
	}
}

// Diagnostic locates a parse failure in one editor buffer, in the coordinates
// the browser textarea uses: Offset counts UTF-16 code units from the start
// of the buffer; Line and Column are 1-based, Column also in UTF-16 code
// units within its line. Message carries no "nextsql syntax:" prefix.
//
// It is advisory. nextsqld's parser/binder stay the sole authority on whether
// a statement is valid, and this covers grammar errors only — an unresolved
// table or column name is reported by the server when the statement actually
// runs, not here (Studio has no catalog of its own to resolve against).
type Diagnostic struct {
	Message string `json:"message"`
	Offset  int    `json:"offset"`
	Line    int    `json:"line"`
	Column  int    `json:"column"`
}

// DiagnosticReport is the editor's live parse-diagnostics response: one entry
// per statement in the buffer that does not parse, in buffer order. Empty
// when the whole buffer parses.
type DiagnosticReport struct {
	Diagnostics []Diagnostic `json:"diagnostics"`
}

// Diagnostics parses every statement in one editor buffer with the same
// grammar the executor uses and returns one location per statement that fails
// to parse (the parser stops at its first error, so never more than one per
// statement). A fully valid buffer returns an empty slice. It opens no driver
// connection and touches no query slot.
//
// An empty or oversized buffer is a request error, matching Analyze. A buffer
// that will not tokenize at all is reported as a single diagnostic at the
// lexer's stopping point rather than an error, so the editor can still point
// the operator at it.
func Diagnostics(sql string) ([]Diagnostic, error) {
	if err := ValidateSQL(sql); err != nil {
		return nil, err
	}
	spans, err := splitStatementSpans(sql)
	if err != nil {
		if _, diag, perr := parser.ParseDiag(sql); perr != nil && diag != nil {
			return []Diagnostic{locateInBuffer(sql, diag.Offset, diag.Message)}, nil
		}
		return nil, nerr.Wrap(nerr.Syntax, "studio.Diagnostics", "script could not be tokenized", err)
	}
	if len(spans) > MaxScriptStatements {
		return nil, nerr.New(nerr.Exhausted, "studio.Diagnostics",
			fmt.Sprintf("script exceeds the %d-statement Studio limit", MaxScriptStatements))
	}
	out := make([]Diagnostic, 0, len(spans))
	for _, sp := range spans {
		frag := sql[sp.start:sp.end]
		_, diag, perr := parser.ParseDiag(frag)
		if perr == nil || diag == nil {
			continue
		}
		off := diag.Offset
		if off < 0 {
			off = 0
		}
		if off > len(frag) {
			off = len(frag)
		}
		out = append(out, locateInBuffer(sql, sp.start+off, diag.Message))
	}
	return out, nil
}

// locateInBuffer converts a byte offset into src to the browser textarea's
// coordinates: a UTF-16 code-unit offset from the buffer start plus a 1-based
// line and (UTF-16) column.
func locateInBuffer(src string, byteOff int, msg string) Diagnostic {
	if byteOff < 0 {
		byteOff = 0
	}
	if byteOff > len(src) {
		byteOff = len(src)
	}
	prefix := src[:byteOff]
	line := 1 + strings.Count(prefix, "\n")
	col := 1 + utf16Len(prefix)
	if i := strings.LastIndexByte(prefix, '\n'); i >= 0 {
		col = 1 + utf16Len(prefix[i+1:])
	}
	return Diagnostic{Message: msg, Offset: utf16Len(prefix), Line: line, Column: col}
}

// utf16Len counts the UTF-16 code units s encodes to (JS string length), so a
// diagnostic offset lands on the right character in the editor even when the
// buffer contains astral-plane runes.
func utf16Len(s string) int {
	n := 0
	for _, r := range s {
		if r > 0xFFFF {
			n += 2
		} else {
			n++
		}
	}
	return n
}

func ValidateSQL(sql string) error {
	if strings.TrimSpace(sql) == "" {
		return nerr.New(nerr.InvalidArgument, "studio.ValidateSQL", "SQL is required")
	}
	if len(sql) > MaxSQLBytes {
		return nerr.New(nerr.Exhausted, "studio.ValidateSQL", "SQL exceeds the 1 MiB Studio limit")
	}
	return nil
}

// ValidateParams bounds a parameterized run: at most MaxQueryParams positional
// values, each at most MaxQueryParamBytes when present. A NULL bind (nil
// Value) has no size.
func ValidateParams(params []QueryParam) error {
	if len(params) > MaxQueryParams {
		return nerr.New(nerr.Exhausted, "studio.ValidateParams",
			fmt.Sprintf("a statement may bind at most %d parameters", MaxQueryParams))
	}
	for _, p := range params {
		if p.Value != nil && len(*p.Value) > MaxQueryParamBytes {
			return nerr.New(nerr.Exhausted, "studio.ValidateParams",
				fmt.Sprintf("a bound parameter value may be at most %d bytes", MaxQueryParamBytes))
		}
	}
	return nil
}

// ParamValues converts editor bind slots to positional driver values. A nil
// slot is a typed SQL NULL; a present slot is bound as a string and coerced
// server-side against the statement's expected parameter type.
func ParamValues(params []QueryParam) []types.Value {
	if len(params) == 0 {
		return nil
	}
	out := make([]types.Value, len(params))
	for i, p := range params {
		if p.Value == nil {
			out[i] = types.Null(types.NullType())
			continue
		}
		out[i] = types.StringValue(*p.Value)
	}
	return out
}

// Collect preserves the bounded M1 JSON endpoint for compatibility and tests.
// On the first row or byte beyond the preview limit it cancels the
// server query and drains/closes the driver Rows so the connection returns to
// a valid protocol frame boundary. Errors produced by that intentional
// cancellation are not reported as query failures; Truncated tells the user
// exactly what happened.
func Collect(ctx context.Context, rows RowStream, cancel context.CancelFunc) (ResultSet, error) {
	if rows == nil {
		return ResultSet{}, nerr.New(nerr.Internal, "studio.Collect", "nil row stream")
	}
	out := ResultSet{
		Columns:     rows.Columns(),
		ColumnTypes: typeNames(rows.ColumnTypes()),
		Rows:        [][]*string{},
	}
	used := resultMetadataBytes(out)

	for rows.Next() {
		if err := ctx.Err(); err != nil {
			_ = rows.Close()
			return ResultSet{}, nerr.Wrap(nerr.Canceled, "studio.Collect", "query canceled", err)
		}
		if len(out.Rows) >= MaxResultRows {
			out.Truncated = true
			cancel()
			_ = rows.Close()
			return out, nil
		}

		vals := rows.Values()
		if len(vals) != len(out.Columns) {
			cancel()
			_ = rows.Close()
			return ResultSet{}, nerr.New(nerr.InvalidFormat, "studio.Collect", "row width does not match result columns")
		}
		rec := make([]*string, len(vals))
		rowBytes := 0
		for i, v := range vals {
			if v.Null {
				continue
			}
			str := v.String()
			rowBytes += len(str)
			if used+rowBytes > MaxResultBytes {
				out.Truncated = true
				cancel()
				_ = rows.Close()
				return out, nil
			}
			rec[i] = &str
		}
		used += rowBytes
		out.Rows = append(out.Rows, rec)
	}
	if err := rows.Err(); err != nil {
		_ = rows.Close()
		return ResultSet{}, err
	}
	out.Affected = rows.Affected()
	if err := rows.Close(); err != nil {
		return ResultSet{}, err
	}
	return out, nil
}

// Stream converts a driver RowStream into bounded batches without
// materializing the full result. emit must consume each frame synchronously;
// Stream reuses no frame slices after emit returns. Cancellation, byte/row
// limits, iterator errors, and emitter failures all close the driver stream
// so its connection returns to a valid protocol boundary.
func Stream(ctx context.Context, rows RowStream, cancel context.CancelFunc, emit func(StreamFrame) error) error {
	if rows == nil {
		return nerr.New(nerr.Internal, "studio.Stream", "nil row stream")
	}
	if cancel == nil {
		return nerr.New(nerr.InvalidArgument, "studio.Stream", "nil cancel function")
	}
	if emit == nil {
		return nerr.New(nerr.InvalidArgument, "studio.Stream", "nil emitter")
	}

	started := time.Now()
	closed := false
	closeRows := func() error {
		if closed {
			return nil
		}
		closed = true
		return rows.Close()
	}
	defer func() { _ = closeRows() }()

	columns := rows.Columns()
	columnTypes := typeNames(rows.ColumnTypes())
	if err := emit(StreamFrame{Type: "meta", Columns: columns, ColumnTypes: columnTypes}); err != nil {
		cancel()
		return nerr.Wrap(nerr.IO, "studio.Stream", "emit metadata", err)
	}

	used := resultMetadataBytes(ResultSet{Columns: columns, ColumnTypes: columnTypes})
	rowCount := 0
	batchBytes := 0
	batch := make([][]*string, 0, StreamBatchRows)
	flush := func() error {
		if len(batch) == 0 {
			return nil
		}
		out := batch
		batch = make([][]*string, 0, StreamBatchRows)
		batchBytes = 0
		if err := emit(StreamFrame{Type: "rows", Rows: out}); err != nil {
			cancel()
			return nerr.Wrap(nerr.IO, "studio.Stream", "emit rows", err)
		}
		return nil
	}
	complete := func(truncated bool) error {
		if err := flush(); err != nil {
			return err
		}
		return emit(StreamFrame{
			Type:      "complete",
			Affected:  rows.Affected(),
			Truncated: truncated,
			ElapsedMS: time.Since(started).Milliseconds(),
			RowCount:  rowCount,
		})
	}

	for rows.Next() {
		if err := ctx.Err(); err != nil {
			cancel()
			return nerr.Wrap(nerr.Canceled, "studio.Stream", "query canceled", err)
		}
		if rowCount >= MaxResultRows {
			cancel()
			_ = closeRows()
			return complete(true)
		}

		vals := rows.Values()
		if len(vals) != len(columns) {
			cancel()
			return nerr.New(nerr.InvalidFormat, "studio.Stream", "row width does not match result columns")
		}
		rec := make([]*string, len(vals))
		rowBytes := 0
		for i, v := range vals {
			if v.Null {
				continue
			}
			str := v.String()
			rowBytes += len(str)
			if rowBytes > StreamRowBytes || used+rowBytes > MaxResultBytes {
				cancel()
				_ = closeRows()
				return complete(true)
			}
			rec[i] = &str
		}
		used += rowBytes
		rowCount++
		if len(batch) > 0 && batchBytes+rowBytes > StreamBatchBytes {
			if err := flush(); err != nil {
				return err
			}
		}
		batchBytes += rowBytes
		batch = append(batch, rec)
		if len(batch) >= StreamBatchRows || batchBytes >= StreamBatchBytes {
			if err := flush(); err != nil {
				return err
			}
		}
	}
	if err := rows.Err(); err != nil {
		return err
	}
	if err := closeRows(); err != nil {
		return err
	}
	return complete(false)
}

func typeNames(in []types.Type) []string {
	out := make([]string, len(in))
	for i := range in {
		out[i] = in[i].String()
	}
	return out
}

func resultMetadataBytes(r ResultSet) int {
	n := 0
	for _, col := range r.Columns {
		n += len(col)
	}
	for _, typ := range r.ColumnTypes {
		n += len(typ)
	}
	return n
}
