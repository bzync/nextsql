const (
	// MaxSQLBytes is below the NSQL protocol's own SQL ceiling and bounds the
	// browser-to-Admin request before it is decoded or sent to nextsqld.
	MaxSQLBytes = 1 << 20
	// MaxResultRows and MaxResultBytes bound both the legacy M1 materialized
	// preview and M2's streaming browser preview.
	MaxResultRows  = 5_000
	MaxResultBytes = 8 << 20
	// StreamBatchRows and StreamBatchBytes keep each browser-facing NDJSON
	// frame bounded while avoiding one HTTP flush and one React update per
	// result row. A single row may exceed StreamBatchBytes, but can never
	// exceed StreamRowBytes; it is emitted alone in that case.
	StreamBatchRows  = 128
	StreamBatchBytes = 256 << 10
	// StreamRowBytes prevents JSON escaping of one adversarial row from
	// turning the 8 MiB aggregate preview budget into a very large single
	// HTTP frame. The result is explicitly truncated before such a row is
	// retained or emitted.
	StreamRowBytes = 1 << 20
	// MaxTables bounds the initial explorer listing. Column and index detail
	// is fetched only when one of these tables is selected.
	MaxTables = 1_000
	// MaxScriptStatements bounds one Execute Script request. Each statement
	// still runs sequentially through the same one-active-query-per-session
	// path as a single statement, so this only bounds how large a single
	// script submission can be, not query concurrency.
	MaxScriptStatements = 200

	// Leave five seconds inside Admin's 30-second HTTP write deadline so a
	// timeout can be canceled, drained, and returned as a structured error.
	QueryTimeout = 25 * time.Second
)

const StreamContentType = "application/x-ndjson"

var queryIDPattern = regexp.MustCompile(`^[A-Za-z0-9_-]{1,128}$`)

// MaxQueryParams bounds one parameterized editor run. NextSQL binds
// positional parameters ($1..$N); the editor sends one slot per referenced
// position, so this also bounds how many placeholders a single run may use.
const MaxQueryParams = 32

// MaxQueryParamBytes bounds one bound value. Values travel as strings and are
// coerced server-side against the statement's expected parameter type — the
// same untyped-string binding path the drivers already rely on — so a value
// larger than this is rejected before it reaches the connection.
const MaxQueryParamBytes = 64 << 10

// QueryParam is one positional bind value for a parameterized editor
// statement. Value is nil for a SQL NULL; otherwise it is a string the server
// coerces to the parameter's expected type. $1 is params[0].
type QueryParam struct {
	Value *string `json:"value"`
}

// QueryRequest is supplied by the editor. QueryID is generated by the
// browser before execution so a concurrent cancellation request can name the
// in-flight query without waiting for the query response. Params, when
// present, are positional bind values for the statement's $1..$N.
type QueryRequest struct {
	QueryID string       `json:"query_id"`
	SQL     string       `json:"sql"`
	Params  []QueryParam `json:"params,omitempty"`
}

// CancelRequest identifies one in-flight query owned by the current Admin
// session. It can never cancel another browser session's connection.
type CancelRequest struct {
	QueryID string `json:"query_id"`
}

// ResultSet is the wire-neutral result shape used by Studio. Cells are
